import numpy as np
import pandas as pd
from scipy.interpolate import interp1d

def compute_vwap(trades: pd.DataFrame, price_col='price', volume_col='volume') -> float:
  total_value = (trades[price_col] * trades[volume_col]).sum()
  total_volume = trades[volume_col].sum()
  return total_value / total_volume

def compute_vwap_slippage(fill_price: float, fill_qty: float, market_vwap: float, side: int) -> float:
  return side * (fill_price - market_vwap) / market_vwap * 10_000

def model_volume_profile(historical_bins: pd.DataFrame, total_adv: float, n_bins: int = 78) -> np.ndarray:
  t_hist = historical_bins['time'].values
  v_hist = historical_bins['vol_pct'].values

  f = interp1d(t_hist, v_hist, kind='cubic', fill_value='extrapolate')
  t_grid = np.linspace(0, 390, n_bins)
  v_profile = np.maximum(0, f(t_grid))
  v_profile /= v_profile.sum()

  return v_profile * total_adv

minutes = np.array([0, 30, 60, 90, 120, 150, 180, 210, 240, 270, 300, 330, 360, 390])
vol_pct = np.array([0.12, 0.07, 0.05, 0.04, 0.04, 0.04, 0.05, 0.05, 0.06, 0.06, 0.07, 0.09, 0.14, 0.12])

historical = pd.DataFrame({'time': minutes, 'vol_pct': vol_pct})
intraday_vol = model_volume_profile(historical, total_adv=10_000_000)

print("Intraday Volume Distribution (5-min bins, first 10):")
times = pd.date_range("09:30", periods=10, freq='5min')
for t, v in zip(times, intraday_vol[:10]):
  bar = '|' * int(v/1_000_000 * 1000)
  print(f"{t.strftime('%H:%M')} {v/1000:6.1f}k - {bar}")

order_window_volume = intraday_vol[:30].sum()
pre_trade_vwap_particiaption = 500_000 / order_window_volume
print(f"\nWindow Volume (09:30-12:00): {order_window_volume:,.0f}shares")
print(f"Participation rate: {pre_trade_vwap_particiaption:.1%}")

print("Strategy: trade exactly pro-rata with market volume => VWAP = market VWAP")

