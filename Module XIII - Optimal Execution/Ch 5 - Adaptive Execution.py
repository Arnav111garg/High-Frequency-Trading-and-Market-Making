  rng = np.random.default_rng(7)
  n_periods = 20
  algo = AdaptiveAlmgrenChriss(X=1_000_000 ,T=1.0 , eta_star=2.5e-6 , lam =1e-6 , n_rebalances=n_periods)
  period_returns = rng.normal(0,0.002,n_periods)
  period_returns[10]=0.025
  for i in range(n_periods):
    algo.update_vol(period_returns[i])
    t_now = i * algo.dt
    trade = algo.next_trade(t_now)
    print(f" period {i:2d} sigma_hat ={algo.sigma_ewma:.5f} "
    f" trade ={trade:9,.0f} remaining ={algo.X_remaining:10,.0f}")

