@dataclass
class QueueState:
    price: float
    side: str
    qty_ahead: int = 0
    our_qty: int = 0
    qty_behind: int = 0
    arrival_time: int = 0

    @property
    def total_qty_at_level(self) -> int:
        return self.qty_ahead + self.our_qty + self.qty_behind

class QueueSimulator:
    def __init__(self, arrival_rate: float, cancel_rate: float,
                 fill_rate: float, tick_size: float = 0.01):
        self.arrival_rate = arrival_rate
        self.cancel_rate = cancel_rate
        self.fill_rate = fill_rate
        self.tick_size = tick_size

    def simulate_queue_evolution(self, initial_state: QueueState,
                                 horizon_sec: float,
                                 n_paths: int = 10000) -> np.ndarray:
        rng = np.random.default_rng(42)
        Q0 = initial_state.qty_ahead
        dt = 1e-3
        n_steps = int(horizon_sec / dt)

        paths = np.full((n_paths,), float(Q0))
        paths = np.maximum(paths, 0)

        for _ in range(n_steps):
            arrivals = rng.poisson(self.arrival_rate * dt, size=n_paths)
            reductions = rng.poisson((self.cancel_rate + self.fill_rate)
                                     * dt * np.maximum(paths, 1), size=n_paths)
            paths = np.maximum(paths + arrivals - reductions, 0)

        return paths

    def fill_probability(self, state: QueueState,
                         incoming_vol_distribution: np.ndarray,
                         n_sim: int = 50000) -> dict:
        Q_ahead = state.qty_ahead
        Q_our = state.our_qty

        fill_probs = np.zeros(n_sim)
        fill_qtys = np.zeros(n_sim)
        rng = np.random.default_rng(0)

        for i in range(n_sim):
            V = rng.choice(incoming_vol_distribution)
            if V <= Q_ahead:
                fill_qty = 0
            elif V <= Q_ahead + Q_our:
                fill_qty = V - Q_ahead
            else:
                fill_qty = Q_our
            fill_probs[i] = 1.0 if fill_qty > 0 else 0.0
            fill_qtys[i] = fill_qty

        return {
            'fill_probability': fill_probs.mean(),
            'expected_fill_qty': fill_qtys.mean(),
            'full_fill_probability': (fill_qtys == Q_our).mean(),
            'partial_fill_prob': ((fill_qtys > 0) & (fill_qtys < Q_our)).mean(),
        }

class QueuePositionEstimator:
    def __init__(self, order_id: int, price: float, side: str,
                 qty: int, queue_state: QueueState):
        self.order_id = order_id
        self.price = price
        self.side = side
        self.qty = qty
        self.state = queue_state

    def on_new_order_at_level(self, order_qty: int, timestamp: int):
        self.state.qty_behind += order_qty

    def on_cancel_at_level(self, cancelled_qty: int, is_ahead: bool):
        if is_ahead:
            self.state.qty_ahead = max(0, self.state.qty_ahead - cancelled_qty)
        else:
            self.state.qty_behind = max(0, self.state.qty_behind - cancelled_qty)

    def on_trade_at_level(self, traded_qty: int):
        if traded_qty <= self.state.qty_ahead:
            self.state.qty_ahead -= traded_qty
        else:
            our_fill = min(traded_qty - self.state.qty_ahead, self.state.our_qty)
            self.state.qty_ahead = 0
            self.state.our_qty = max(0, self.state.our_qty - our_fill)
            return our_fill
        return 0

    def queue_ahead(self) -> int:
        return self.state.qty_ahead

    def estimated_fill_time(self, avg_fill_rate_per_sec: float) -> float:
        if avg_fill_rate_per_sec <= 0:
            return float('inf')
        return self.state.qty_ahead / avg_fill_rate_per_sec

