class MatchingEngine:
    def __init__(self, instrument: str, tick_size: float = 0.01):
        self.instrument = instrument
        self.tick_size = tick_size
        self.lob = LimitOrderBook(instrument, tick_size)
        self.order_seq = 0
        self.fills: List[Fill] = []
        self.time_ns: int = 0

    def _next_id(self) -> int:
        self.order_seq += 1
        return self.order_seq

    def _now(self) -> int:
        return self.time_ns

    def submit(self, side: Side, price: Optional[float], qty: int,
               order_type: OrderType = OrderType.LIMIT,
               peak_qty: Optional[int] = None) -> List[Fill]:
        default_price = float('inf') if side == Side.BUY else 0.0
        actual_price = price if price is not None else default_price

        o = Order(
            order_id=self._next_id(),
            price=actual_price,
            quantity=qty,
            side=side.value,
            order_type=order_type.value,
            timestamp=self._now(),
        )
        if order_type == OrderType.ICEBERG and peak_qty is not None:
            o._peak_qty = peak_qty
            o._reserve_qty = qty - peak_qty
            o.remaining = peak_qty

        if order_type == OrderType.FOK:
            if not self._can_fully_fill(o):
                return []

        new_fills = self._match(o)

        if o.remaining > 0:
            if order_type == OrderType.LIMIT:
                self._add_to_book(o)
            elif order_type == OrderType.ICEBERG:
                self._replenish_iceberg(o)

        return new_fills

    def _can_fully_fill(self, order: Order) -> bool:
        avail = 0
        book = self.lob.asks if order.side == 'BUY' else self.lob.bids
        for neg_p, lvl in book.items():
            p = -neg_p if order.side == 'BUY' else neg_p
            if order.side == 'BUY' and p > order.price:
                break
            if order.side == 'SELL' and p < order.price:
                break
            avail += lvl.total_quantity
        return avail >= order.remaining

    def _match(self, aggressor: Order) -> List[Fill]:
        fills = []
        if aggressor.side == 'BUY':
            opposite = self.lob.asks
            price_ok = lambda rp: rp <= aggressor.price
            key_sign = +1
        else:
            opposite = self.lob.bids
            price_ok = lambda rp: rp >= aggressor.price
            key_sign = -1

        while aggressor.remaining > 0 and opposite:
            best_key, best_level = next(iter(opposite.items()))
            rest_price = key_sign * best_key

            if not price_ok(rest_price):
                break

            while aggressor.remaining > 0 and best_level.orders:
                passive = best_level.orders[0]
                fill_qty = min(aggressor.remaining, passive.remaining)

                f = Fill(
                    aggressive_id=aggressor.order_id,
                    passive_id=passive.order_id,
                    price=rest_price,
                    quantity=fill_qty,
                    timestamp=self._now(),
                )
                fills.append(f)
                self.fills.append(f)

                aggressor.remaining -= fill_qty
                passive.remaining -= fill_qty

                if passive.is_filled:
                    best_level.orders.popleft()
                    del self.lob.orders[passive.order_id]

            if not best_level.orders:
                del opposite[best_key]
        return fills

    def _add_to_book(self, order: Order):
        if order.side == 'BUY':
            key = -order.price
            book = self.lob.bids
        else:
            key = order.price
            book = self.lob.asks

        if key not in book:
            book[key] = PriceLevel(price=order.price)
        book[key].orders.append(order)
        self.lob.orders[order.order_id] = order

    def _replenish_iceberg(self, order: Order):
        if hasattr(order, '_reserve_qty') and order._reserve_qty > 0:
            refill = min(order._peak_qty, order._reserve_qty)
            order.remaining = refill
            order._reserve_qty -= refill
            order.timestamp = self._now()
            self._add_to_book(order)

    def cancel(self, order_id: int) -> bool:
        if order_id not in self.lob.orders:
            return False
        o = self.lob.orders[order_id]
        book = self.lob.bids if o.side == 'BUY' else self.lob.asks
        key = -o.price if o.side == 'BUY' else o.price
        lvl = book.get(key)
        if lvl:
            try:
                lvl.orders.remove(o)
            except ValueError:
                pass
            if not lvl.orders:
                del book[key]
            del self.lob.orders[order_id]
            return True
        return False

