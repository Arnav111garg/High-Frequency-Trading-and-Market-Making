class LatencyModel:
    def __init__(self, model_type: str = 'lognormal'):
        self.model_type = model_type
        self.params: Dict = {}
        self.rng = np.random.default_rng(42)

    def fit(self, samples: np.ndarray) -> Dict:
        samples = np.asarray(samples)
        assert (samples > 0).all(), "Latency samples must be positive"

        if self.model_type == 'lognormal':
            mu, sigma = np.log(samples).mean(), np.log(samples).std()
            self.params = {'mu': mu, 'sigma': sigma}
            print(f"LogNormal fit: mu={mu:.4f}, sigma={sigma:.4f}")
            print(f"E[L] = {np.exp(mu + 0.5 * sigma**2):.2f} ns")
            print(f"P99 = {stats.lognorm(sigma, scale=np.exp(mu)).ppf(0.99):.2f} ns")

        elif self.model_type == 'weibull':
            shape, _, scale = stats.weibull_min.fit(samples, floc=0)
            self.params = {'shape': shape, 'scale': scale}

        elif self.model_type == 'empirical':
            self.params = {'samples': np.sort(samples)}

        elif self.model_type == 'mixture':
            self._fit_mixture(samples)

        return self.params

    def _fit_mixture(self, samples: np.ndarray, n_components: int = 2):
        log_s = np.log(samples)
        n = len(log_s)
        q75 = np.percentile(log_s, 75)
        mask = log_s <= q75

        pi1 = mask.mean()
        mu1, sig1 = log_s[mask].mean(), log_s[mask].std() + 1e-6
        mu2, sig2 = log_s[~mask].mean(), log_s[~mask].std() + 1e-6

        for _ in range(100):
            r1 = pi1 * stats.norm.pdf(log_s, mu1, sig1)
            r2 = (1 - pi1) * stats.norm.pdf(log_s, mu2, sig2)
            r1 = r1 / (r1 + r2 + 1e-300)

            pi1 = r1.mean()
            mu1 = (r1 * log_s).sum() / (r1.sum() + 1e-10)
            sig1 = np.sqrt((r1 * (log_s - mu1)**2).sum() / (r1.sum() + 1e-10)) + 1e-6
            mu2 = ((1 - r1) * log_s).sum() / ((1 - r1).sum() + 1e-10)
            sig2 = np.sqrt(((1 - r1) * (log_s - mu2)**2).sum() / ((1 - r1).sum() + 1e-6)) + 1e-6

        self.params = {
            'type': 'mixture',
            'pi': [pi1, 1 - pi1],
            'mu': [mu1, mu2],
            'sigma': [sig1, sig2]
        }

    def sample(self, n: int = 1) -> np.ndarray:
        if self.model_type == 'lognormal':
            return self.rng.lognormal(self.params['mu'], self.params['sigma'], n)

        elif self.model_type == 'weibull':
            return stats.weibull_min.rvs(self.params['shape'], scale=self.params['scale'], size=n, random_state=self.rng)

        elif self.model_type == 'empirical':
            return self.rng.choice(self.params['samples'], n)

        elif self.model_type == 'mixture':
            components = self.rng.choice(len(self.params['pi']), size=n, p=self.params['pi'])
            result = np.zeros(n)
            for k, (mu, sig) in enumerate(zip(self.params['mu'], self.params['sigma'])):
                mask = components == k
                result[mask] = np.exp(self.rng.normal(mu, sig, mask.sum()))
            return result

        raise ValueError(f"Unknown model_type: {self.model_type}")

    def alpha_decay_factor(self, signal_halflife_ns: float) -> float:
        decay_rate = np.log(2) / signal_halflife_ns
        L_samples = self.sample(100_000)
        return np.mean(np.exp(-decay_rate * L_samples))

class LatencyAwareSimulator:
    def __init__(self, me: 'MatchingEngine', latency_model: LatencyModel, correlation_rho: float = 0.3):
        self.me = me
        self.lat_model = latency_model
        self.rho = correlation_rho
        self._last_lat = None

    def submit_with_latency(self, side, price, qty, current_time_ns: int):
        if self._last_lat is None:
            lat_ns = self.lat_model.sample(1)[0]
        else:
            base = self.lat_model.sample(1)[0]
            lat_ns = (self.rho * self._last_lat + np.sqrt(1 - self.rho**2) * base)
            lat_ns = abs(lat_ns)
        self._last_lat = lat_ns

        arrival_time = int(current_time_ns + lat_ns)
        self.me.time_ns = arrival_time

        return self.me.submit(side, price, qty), lat_ns

