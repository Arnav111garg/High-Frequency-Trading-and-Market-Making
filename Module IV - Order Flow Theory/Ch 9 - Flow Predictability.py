def build_flow_prediction_features(trades_quotes: pd.DataFrame, n_lags: int = 20) -> pd.DataFrame:
  df = trades_quotes.copy()
  features = {}

  for k in range(1, n_lags + 1):
    features[f'flow_lag_{k}'] = df['signed_volume'].shift(k)

  df['mid_return'] = df['midpoint'].pct_change()
  for k  in range(1, 10):
    features[f'ret_lag_{k}'] = df['mid_return'].shift(k)

  df['spread'] = df['best_ask'] - df['best_bid']
  df['depth_imbalance'] = ((df.get('bid_depth', df['best_bid']) - df.get('ask_depth', df['best_ask'])) / (df.get('bid_depth', df['best_bid']) + df.get('ask_depth', df['best_ask']) + 1e-10))

  features['spread'] = df['spread']
  features['depth_imbalance'] = df['depth_imbalance']

  for window in [5, 10, 20]:
    features[f'flow_ma_{window}'] = df['signed_volume'].rolling(window).mean()
    features[f'flow_std_{window}'] = df['signed_volume'].rolling(window).std()
    features[f'vol_ma_{window}'] = df['signed_volume'].abs().rolling(window).mean()

  df['tod_sec'] = (pd.to_datetime(df['time']).dt.hour * 3600 + pd.to_datetime(df['time']).dt.minute * 60 + pd.to_datetime(df['time']).dt.second)
  features['tod_sin'] = np.sin(2 * np.pi * df['tod_sec'] / 23400)
  features['tod_cos'] = np.cos(2 * np.pi * df['tod_sec'] / 23400)

  X = pd.DataFrame(features)
  y = np.sign(df['signed_volume'])

  return X.dropna(), y.loc[X.dropna().index]

def train_xgb_flow_predictor(X: pd.DataFrame, y: pd.Series, n_splits: int = 5) -> dict:
  y_binary = (y > 0).astype(int)

  tscv = TimeSeriesSplit(n_splits=n_splits)
  val_accuracies = []
  val_log_losses = []
  feature_importances = []

  params = {'max_depth': 6,
            'learning_rate': 0.05, 'n_estimators': 500, 'subsample': 0.8, 'min_child_weight': 10, 'gamma': 0.1, 'use_label_encoder': False, 'eval_metric': 'logloss', 'treemethid': 'hist', 'random_state': 12}

  models = []
  for fold, (train_idx, val_idx) in enumerate(tscv.split(X)):
    X_train, X_val = X.iloc[train_idx], X.iloc[val_idx]
    y_train, y_val = y_binary.iloc[train_idx], y_binary.iloc[val_idx]

    model = xgb.XGBClassifier(**params)
    model.fit(X_train, y_train, eval_set=[(X_val, y_val)], verbose=False)

    proba = model.predict_proba(X_val)[:, 1]
    preds = (proba > 0.5).astype(int)

    acc = accuracy_score(y_val, preds)
    ll = log_loss(y_val, proba)
    val_accuracies.append(acc)
    val_log_losses.append(ll)
    feature_importances.append(model.feature_importances_)
    models.append(model)

    print(f"Fold {fold+1}: Acc={acc:.4f}, LogLoss={ll:.4f}")

  avg_acc = np.mean(val_accuracies)
  avg_ll = np.mean(val_log_losses)
  avg_fi = np.mean(feature_importances, axis=0)

  print(f"\nAverage Accuracy: {avg_acc:.4f} {np.std(val_accuracies):.4f}")
  print(f"Average LogLoss: {avg_ll:.4f} {np.std(val_log_losses):.4f}")

  fi_df = pd.DataFrame({'feature': X.columns, 'importance': avg_fi}).sort_values('importance', ascending=False)
  print("\nTop 10 features:\n", fi_df.head(10).to_string())

  return {'models': models, 'val_accuracies': val_accuracies, 'feature_importance': fi_df, 'mean_accuracy': avg_acc}

