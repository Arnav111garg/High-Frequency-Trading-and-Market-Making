def hawkes_log_likelihood(params: np.ndarray, event_times_buy: np.ndarray, event_times_sell: np.ndarray, T: float) -> float:
  (mu_b, mu_s, a_bb, b_bb, a_bs, b_bs, a_sb, b_sb, a_ss, b_ss) = params

  if any(p <= 0 for p in params):
    return 1e10

  if a_bb >= b_bb or a_ss >= b_ss:
    return 1e10

  ll_b = 0.0
  for t in event_times_buy:
    lam_b = mu_b
    lam_b += a_bb * np.sum(np.exp(-b_bb * (t - event_times_buy[event_times_buy < t])))
    lam_b += a_bs * np.sum(np.exp(-b_bs * (t - event_times_sell[event_times_sell < t])))
    lam_b = max(lam_b, 1e-10)
    ll_b += np.log(lam_b)

  comp_b = mu_b * T

  for s in event_times_buy:
    comp_b += (a_bb/b_bb) * (1 - np.exp(-b_bb * (T - s)))
  for s in event_times_sell:
    comp_b += (a_bs/b_bs) * (1 - np.exp(-b_bs * (T - s)))

  ll_s = 0.0
  for t in event_times_sell:
    lam_s = mu_s
    lam_s += a_ss * np.sum(np.exp(-b_ss * (t - event_times_sell[event_times_sell < t])))
    lam_s += a_sb * np.sum(np.exp(-b_sb * (t - event_times_buy[event_times_buy < t])))
    lam_s = max(lam_s, 1e-10)
    ll_s += np.log(lam_s)

  comp_s = mu_s * T
  for s in event_times_sell:
    comp_s += (a_ss/b_ss) * (1 - np.exp(-b_ss * (T - s)))
  for s in event_times_buy:
    comp_s += (a_sb/b_sb) * (1 - np.exp(-b_sb * (T - s)))

  total_ll = ll_b - comp_b + ll_s - comp_s
  return -total_ll

