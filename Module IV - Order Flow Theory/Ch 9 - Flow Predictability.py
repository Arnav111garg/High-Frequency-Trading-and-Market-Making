def fit_as_flow_model(flow: pd.Series, returns: pd.Series, max_lags_flow: int = 20, max_lags_ret: int = 10, select_lags: bool = True) -> dict:
  if select_lags:
    best_bic = np.inf
    best_k, best_j = 1, 1

    for k in range(1, max_lags_flow + 1):
      for j in range(0, max_lags_ret + 1):
        X_data = {}
        for lag in range(1, k+1):
          X_data[f'flow_lag{lag}'] = flow.shift(lag)
        for lag in range(1, k+1):
          X_data[f'ret_lag{lag}'] = returns.shift(lag)

        df_model = pd.DataFrame(X_data).assign(y=flow).dropna()
        X = s.add_constant(df_model.drop('y', axis=1))
        y = df_model['y']

        try:
          m = sm.OLS(y, X).fit()
          if m.bic < best_bic:
            best_bic = m.bic
            best_k, best_j = k, j
        except:
          continue

    K, J = best_k, best_j
    print(f"Optimal lags: K={K} (flow), J={J} (return)")
  else:
    K, J = max_lags_flow, max_lags_ret

  X_data = {}
  for lag in range(1, K+1):
    X_data[f'flow_lag{lag}'] = flow.shift(lag)
  for lag in range(1, J+1):
    X_data[f'ret_lag{lag}'] = returns.shift(lag)

  df_model = pd.DataFrame(X_data).assign(y=flow).dropna()
  X = sm.add_constant(df_model.drop('y', axis=1))
  y = df_model['y']

  model = sm.OLS(y, X).fit(cov_type='HAC', cov_kwds={'maxlags': 10})
  print(model.summary())

  return {'model': model, 'K': K, 'J': J, 'bic': model.bic}

