# AUTOCORRELATION ANALYSIS


def compute_event_acf ( events : np. ndarray , max_lag : int = 20 ,
                      bin_size : float = 0.1) -> np. ndarray :
  """
  Compute autocorrelation function of the binned counting process .
  Bins events into intervals of size bin_size , then compute ACF .
  """
  from statsmodels .tsa. stattools import acf
  T_max = events [ -1] if len( events ) > 0 else 1.0
  bins = np. arange (0 , T_max + bin_size , bin_size )
  counts , _ = np. histogram (events , bins = bins )
  acf_values = acf (counts , nlags = max_lag , fft= True ) [1:] # exclude lag 0
  return acf_values


