import numpy as np
from dataclasses import dataclass
from typing import List , Tuple , Optional
import matplotlib . pyplot as plt


@dataclass
class HawkesParams :
  """ Parameters for exponential - kernel univariate Hawkes process ."""

  mu : float # Baseline intensity
  alpha : float # Jump size per event ( branching ratio = alpha )
  beta : float # Decay rate

  def __post_init__ ( self ) :
    if self . alpha >= 1.0:
      raise ValueError ( f"Branching ratio alpha ={self.alpha:.4f} >= 1: process will explode !")
    if self . mu <= 0 or self . beta <= 0:
      raise ValueError ("mu and beta must be positive ")

  @property
  def mean_intensity ( self ) -> float :
    """ Stationary mean intensity E[ lambda ] = mu / (1 - alpha )."""
    return self . mu / (1.0 - self . alpha )

  @property
  def branching_ratio ( self ) -> float :
    return self . alpha


class HawkesSimulator :
  """
  Simulate a univariate Hawkes process using Ogata's modified thinning
  algorithm . This is the standard production algorithm .

  Reference : Ogata (1981) , "On Lewis' simulation method for point processes " ,
  IEEE Transactions on Information Theory .
  """

  def __init__ ( self , params : HawkesParams , seed : Optional [int] = None ):
    self . params = params
    self .rng = np. random . default_rng ( seed )

  def intensity (self , t: float , events : np. ndarray ) -> float :
    """
    Compute lambda (t) given past events .

    lambda (t) = mu + alpha * beta * sum_ { tau_i < t} exp( - beta *(t - tau_i ))
    """
    mu , alpha , beta = self . params .mu , self . params .alpha , self . params . beta
    past = events [ events < t]
    return mu + alpha * beta * np.sum(np.exp( - beta * (t - past )))

  def simulate (self , T: float ) -> np. ndarray :
    """
    Ogata thinning algorithm for exact simulation of Hawkes process .

    Returns array of event times in [0 , T].
    """
    mu , alpha , beta = self . params .mu , self . params .alpha , self . params . beta

    events = []
    t = 0.0

    # Current upper bound on intensity
    lambda_bar = mu # starts at baseline (no events yet)

    while t < T:
      # Step 1: Draw next candidate time from homogeneous Poisson (lambda_bar )
      t += self .rng . exponential (1.0 / lambda_bar )

      if t >= T:
        break

      # Step 2: Compute true intensity at candidate time
      lambda_t = self . intensity (t, np. array ( events ) if events else np. array ([]) )

      # Step 3: Accept / reject
      u = self .rng . uniform (0 , 1)
      if u <= lambda_t / lambda_bar :
        events . append (t)
        # Update upper bound : jump by alpha * beta at new event
        lambda_bar = lambda_t + alpha * beta
      else :
        # Rejected : update upper bound to true value ( tighter bound )
        lambda_bar = lambda_t

    return np. array ( events )

  def simulate_path (self , T: float , dt: float = 0.001) -> Tuple [np. ndarray , np. ndarray ]:
    """
    Return ( time_grid , intensity_path ) for plotting .
    Events are simulated first , then intensity is evaluated on grid .
    """
    events = self . simulate (T)
    time_grid = np. arange (0 , T, dt)
    intensity_path = np. array ([
        self . intensity (t, events ) for t in time_grid
    ])
    return time_grid , intensity_path , events

