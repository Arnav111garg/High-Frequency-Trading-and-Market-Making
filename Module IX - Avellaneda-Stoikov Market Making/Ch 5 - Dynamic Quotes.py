def simulate_as_market_maker(S0 =100.0, sigma=0.02, gamma =0.1, k=1.5, A=10.0, T=60.0, dt=1/60.0, n_paths=200, q_max=20, seed=12):
  np.random.seed(seed)
  n_steps = int(T/dt)
  results = {'pnl ': [] , 'inventory ': [] , 'spread ': [] , 'ask ': [] , 'bid ': [] , 'mid ': []}
  all_final_pnl = []

  for path in range(n_paths):
    S = S0
    q = 0
    X = 0

    for step in range(n_steps):
      t = step * dt
      T_minus_t = max(T - t, dt)
      r = S - q * gamma * sigma **2 * T_minus_t
      half_spread = 0.5 * (gamma * sigma **2 * T_minus_t + (2/ gamma) * np.log (1 + gamma / k))
      ask = r + half_spread
      bid = r - half_spread
      delta_a = ask - S if q < q_max else np.inf
      delta_b = S - bid if q > - q_max else np.inf
      p_ask = (1 - np.exp (-A * np.exp(-k * delta_a ) * dt)) if delta_a < np.inf else 0
      p_bid = (1 - np.exp (-A * np.exp(-k * delta_b ) * dt)) if delta_b < np.inf else 0
      fill_ask = np.random.binomial (1 , p_ask)
      fill_bid = np.random.binomial (1 , p_bid)
      X += fill_ask * ask - fill_bid * bid
      q += fill_bid - fill_ask
      S += sigma * np.sqrt ( dt ) * np.random.randn ()

    W_T = X + q * S
    all_final_pnl.append ( W_T )
  return pd.Series( all_final_pnl )

