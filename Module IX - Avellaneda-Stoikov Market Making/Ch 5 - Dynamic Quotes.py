class QuoteUpdateReason(Enum):
  MID_PRICE_MOVE = "mid_price_move"
  FILL_EVENT = "fill_event"
  TIME_DECAY = "time_decay"
  RECALIBRATION = "recalibration"
  HARD_CONSTRAINT = "hard_constraint"

class DynamicASQuoter:
  def __init__(self, params, min_quote_life=0.01,
               max_quote_age=1.0):
    self.p = params
    self.min_quote_life = min_quote_life
    self.max_quote_age = max_quote_age

    self.current_ask = None
    self.current_bid = None
    self.last_quote_time = 0.0
    self.inventory = 0
    self.S = None
    self.session_start = time.time()

  def t_elapsed(self):
    return (time.time() - self.session_start) / 60.0

  def should_requote(self, reason, new_S=None):
    age = time.time() - self.last_quote_time

    if age < self.min_quote_life:
      return False
    if age > self.max_quote_age:
      return True
    if reason in [QuoteUpdateReason.FILL_EVENT,
                  QuoteUpdateReason.HARD_CONSTRAINT]:
      return True
    if reason == QuoteUpdateReason.MID_PRICE_MOVE and new_S is not None:
      return abs(new_S - self.S) >= 0.01
    return False

  def compute_and_send_quotes(self, reason):
    t = self.t_elapsed()
    T_minus_t = max(self.p['T'] - t, 0.001)

    r = self.S - self.inventory * self.p['gamma'] * \
        self.p['sigma']**2 * T_minus_t
    half_spread = 0.5 * (
        self.p['gamma'] * self.p['sigma']**2 * T_minus_t +
        (2/self.p['gamma']) * np.log(1 + self.p['gamma']/
                                     self.p['k'])
    )

    new_ask = r + half_spread
    new_bid = r - half_spread

    if new_ask != self.current_ask or new_bid != self.current_bid:
      self._cancel_quotes()
      self._send_quotes(new_ask, new_bid)
      self.current_ask = new_ask
      self.current_bid = new_bid
      self.last_quote_time = time.time()

    return new_ask, new_bid

  def on_market_data(self, new_S):
    old_S = self.S
    self.S = new_S
    if self.should_requote(QuoteUpdateReason.MID_PRICE_MOVE, new_S):
      self.compute_and_send_quotes(QuoteUpdateReason.MID_PRICE_MOVE)

  def on_fill(self, side, size=1):
    if side == 'bid':
      self.inventory += size
    else:
      self.inventory -= size
    self.compute_and_send_quotes(QuoteUpdateReason.FILL_EVENT)

